alter table public.matches enable row level security;
alter table public.bookings enable row level security;

grant select on public.matches to anon, authenticated;
grant update (available_seats) on public.matches to anon, authenticated;
grant insert on public.bookings to anon, authenticated;
grant usage, select on sequence public.bookings_id_seq to anon, authenticated;

drop policy if exists "Matches are visible to everyone" on public.matches;
create policy "Matches are visible to everyone"
  on public.matches for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can update available seats" on public.matches;
create policy "Anyone can update available seats"
  on public.matches for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Anyone can create a booking" on public.bookings;
create policy "Anyone can create a booking"
  on public.bookings for insert
  to anon, authenticated
  with check (true);

